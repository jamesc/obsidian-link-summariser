"""
Custom evaluation metrics for summary quality assessment.

Implements metrics for:
- Tag accuracy (precision, recall, F1 score)
- Content type classification accuracy
- Summary quality scores

These metrics can be used standalone or synced to Langfuse as trace scores.
"""

import logging
from dataclasses import dataclass
from typing import Any

__all__ = [
    "MetricResult",
    "TagAccuracyMetric",
    "ContentTypeAccuracyMetric",
    "evaluate_summary_result",
]

logger = logging.getLogger(__name__)


@dataclass
class MetricResult:
    """
    Result from evaluating a metric.

    Attributes:
        name: Metric name (e.g., "tag_accuracy", "content_type_accuracy").
        scores: Dictionary of score names to values (0.0-1.0).
        details: Additional details about the evaluation.
    """

    name: str
    scores: dict[str, float]
    details: dict[str, Any] | None = None

    @property
    def primary_score(self) -> float:
        """
        Get the primary score for this metric.

        For tag accuracy, returns F1 score.
        For content type, returns accuracy.
        """
        if "f1_score" in self.scores:
            return self.scores["f1_score"]
        if "accuracy" in self.scores:
            return self.scores["accuracy"]
        # Return first score if no primary identified
        return next(iter(self.scores.values()), 0.0)


class TagAccuracyMetric:
    """
    Evaluate accuracy and relevance of suggested tags.

    Computes precision, recall, and F1 score by comparing
    generated tags against expected tags.
    """

    def evaluate(
        self,
        suggested_tags: list[str],
        expected_tags: list[str] | None,
    ) -> MetricResult:
        """
        Evaluate tag accuracy.

        Args:
            suggested_tags: Tags generated by the summarizer.
            expected_tags: Expected/reference tags for comparison.

        Returns:
            MetricResult with precision, recall, and F1 scores.
        """
        # Handle case where no expected tags provided
        if not expected_tags:
            logger.debug("No expected tags provided, skipping tag accuracy evaluation")
            return MetricResult(
                name="tag_accuracy",
                scores={
                    "precision": 1.0,  # Assume all suggested tags are valid
                    "recall": 0.0,     # Can't compute recall without expected
                    "f1_score": 0.0,   # Can't compute F1 without expected
                },
                details={
                    "suggested_tags": suggested_tags,
                    "expected_tags": [],
                    "true_positives": [],
                    "false_positives": suggested_tags,
                    "false_negatives": [],
                    "note": "No expected tags provided for comparison",
                },
            )

        # Normalize tags for comparison (lowercase, stripped)
        suggested_set = {tag.lower().strip() for tag in suggested_tags if tag}
        expected_set = {tag.lower().strip() for tag in expected_tags if tag}

        # Calculate set intersections
        true_positives = suggested_set & expected_set
        false_positives = suggested_set - expected_set
        false_negatives = expected_set - suggested_set

        # Calculate precision: what fraction of suggested tags are correct
        precision = len(true_positives) / len(suggested_set) if suggested_set else 0.0

        # Calculate recall: what fraction of expected tags were found
        recall = len(true_positives) / len(expected_set) if expected_set else 0.0

        # Calculate F1 score: harmonic mean of precision and recall
        if precision + recall > 0:
            f1_score = 2 * (precision * recall) / (precision + recall)
        else:
            f1_score = 0.0

        return MetricResult(
            name="tag_accuracy",
            scores={
                "precision": precision,
                "recall": recall,
                "f1_score": f1_score,
            },
            details={
                "suggested_tags": list(suggested_set),
                "expected_tags": list(expected_set),
                "true_positives": list(true_positives),
                "false_positives": list(false_positives),
                "false_negatives": list(false_negatives),
            },
        )


class ContentTypeAccuracyMetric:
    """
    Evaluate content type classification accuracy.

    Simple binary metric - either the content type matches or it doesn't.
    """

    def evaluate(
        self,
        predicted_type: str,
        expected_type: str | None,
    ) -> MetricResult:
        """
        Evaluate content type classification.

        Args:
            predicted_type: Content type predicted by summarizer.
            expected_type: Expected content type for comparison.

        Returns:
            MetricResult with accuracy score.
        """
        if not expected_type:
            logger.debug("No expected content type provided, skipping evaluation")
            return MetricResult(
                name="content_type_accuracy",
                scores={"accuracy": 1.0},  # Assume correct if no expectation
                details={
                    "predicted_type": predicted_type,
                    "expected_type": None,
                    "note": "No expected content type provided for comparison",
                },
            )

        # Normalize for comparison (lowercase, stripped)
        predicted_normalized = predicted_type.lower().strip()
        expected_normalized = expected_type.lower().strip()

        is_match = predicted_normalized == expected_normalized

        return MetricResult(
            name="content_type_accuracy",
            scores={"accuracy": 1.0 if is_match else 0.0},
            details={
                "predicted_type": predicted_type,
                "expected_type": expected_type,
                "match": is_match,
            },
        )


def evaluate_summary_result(
    summary_content: str,
    summary_tags: list[str],
    summary_content_type: str,
    expected_tags: list[str] | None = None,
    expected_content_type: str | None = None,
    url: str | None = None,
) -> dict[str, MetricResult]:
    """
    Run all evaluation metrics on a summary result.

    Convenience function that runs tag accuracy and content type
    metrics and returns combined results.

    Args:
        summary_content: The generated summary text.
        summary_tags: Tags suggested by the summarizer.
        summary_content_type: Content type classification from summarizer.
        expected_tags: Expected tags for comparison (optional).
        expected_content_type: Expected content type for comparison (optional).
        url: Source URL for logging context (optional).

    Returns:
        Dictionary mapping metric names to MetricResult objects.
    """
    metrics: dict[str, MetricResult] = {}

    # Tag accuracy
    tag_metric = TagAccuracyMetric()
    metrics["tag_accuracy"] = tag_metric.evaluate(
        suggested_tags=summary_tags,
        expected_tags=expected_tags,
    )

    # Content type accuracy
    type_metric = ContentTypeAccuracyMetric()
    metrics["content_type_accuracy"] = type_metric.evaluate(
        predicted_type=summary_content_type,
        expected_type=expected_content_type,
    )

    # Log results
    if url:
        logger.info(
            "Evaluation for %s: tag_f1=%.2f, content_type_acc=%.2f",
            url,
            metrics["tag_accuracy"].primary_score,
            metrics["content_type_accuracy"].primary_score,
        )

    return metrics
